"""E17 (certified ABC rewrites) -> paper/numbers_e17.tex and gpu_results/E17/e17_numbers.json.
Sources: the server's results/E17/summary.csv (seed means, the same aggregation as every other GPU number) and, for the
per-family values, the raw records (raw_abc.pkl) of the same runs, recomputed with core.stats.
  python make_e17.py <extracted results dir>"""
import csv, glob, json, os, pickle, sys, numpy as np
sys.path.insert(0, '..')
from core.stats import group_metrics, seed_values  # noqa: E402

X = sys.argv[1]
OUT_TEX = 'work/paper/numbers_e17.tex'
OUT_DIR = 'work_gpu/gpu_results/E17'
os.makedirs(OUT_DIR, exist_ok=True)
S = list(csv.DictReader(open(os.path.join(X, 'results/E17/summary.csv'))))


def row(exp, suite, arch, method, config_has=None):
    m = [r for r in S if r['exp'] == exp and r['suite'] == suite and r['arch'] == arch and r['method'] == method
         and (config_has is None or config_has in r['config'])]
    assert len(m) == 1, (exp, suite, arch, method, config_has, len(m))
    return m[0]


def v(r, k):
    return float(r[k + '_mean'])


def fam(pattern, kinds, key='top1_rs'):
    vals = []
    for f in sorted(glob.glob(os.path.join(X, pattern, 'raw_abc.pkl'))):
        g = group_metrics(pickle.load(open(f, 'rb')), kinds=kinds)
        vals.append(np.nanmean(g[key]) * (100 if key == 'top1_rs' else 1))
    assert len(vals) == 5, (pattern, len(vals))
    return float(np.mean(vals))


N = {}
D64, D256 = 'gru_d64_r2', 'gru_d256_r2'
b64, e64 = row('E1a', 'abc', D64, 'base'), row('E1a', 'abc', D64, 'eqalign_ph')
b256, e256 = row('E1a', 'abc', D256, 'base'), row('E1a', 'abc', D256, 'eqalign_ph')
N['AbcBaseTop'], N['AbcOursTop'] = v(b64, 'top1_abc'), v(e64, 'top1_abc')
N['AbcBaseTopSyn'], N['AbcOursTopSyn'] = v(b64, 'top1_syn'), v(e64, 'top1_syn')       # = paper BaseTopSyn / OursTopSyn
N['AbcWBaseTop'], N['AbcWOursTop'] = v(b256, 'top1_abc'), v(e256, 'top1_abc')
N['AbcBaseRho'], N['AbcBaseRhoSyn'] = v(b64, 'rho_abc'), v(b64, 'rho_syn')
N['AbcBaseDMAE'] = v(b64, 'dMAE_abc')
N['AbcBaseTopLut'], N['AbcOursTopLut'] = v(b64, 'top1_lutmap'), v(e64, 'top1_lutmap')
P = {'base': 'runs/E1a/gru_d64_r2/base_lr0.002_s*', 'ours': 'runs/E1a/gru_d64_r2/eqalign_ph_l0.2_lr0.002_s*'}
N['AbcBaseTopDc'], N['AbcOursTopDc'] = fam(P['base'], ['A2_dc2']), fam(P['ours'], ['A2_dc2'])
N['AbcBaseTopRw'], N['AbcOursTopRw'] = fam(P['base'], ['A1_resyn2']), fam(P['ours'], ['A1_resyn2'])
N['AbcBaseTopCr'], N['AbcOursTopCr'] = fam(P['base'], ['A3_compress2rs']), fam(P['ours'], ['A3_compress2rs'])
# baseline rho over every architecture and width (GRU 64, 256, 1024; bidirectional 64-256; transformer 128-512)
rhos = {r['arch']: v(r, 'rho_abc') for r in S if r['suite'] == 'abc' and r['method'] == 'base' and r['exp'] in ('E1a', 'E2', 'E15')}
rsyn = {r['arch']: v(r, 'rho_syn') for r in S if r['suite'] == 'abc' and r['method'] == 'base' and r['exp'] in ('E1a', 'E2', 'E15')}
N['AbcAllRhoMin'], N['AbcAllRhoMax'] = min(rhos.values()), max(rhos.values())
N['AbcAllRhoSynMin'], N['AbcAllRhoSynMax'] = min(rsyn.values()), max(rsyn.values())
N['AbcNArch'] = len(rhos)
# DeepGate2 (GPU runs, shared primary inputs, seed 0): released, fine-tuned with its own loss, with EqAlign (5 epochs)
N['AbcDTwoTop'] = v(row('E3', 'abc', 'deepgate2', 'dg2_released'), 'top1_abc')
N['AbcDTwoRho'] = v(row('E3', 'abc', 'deepgate2', 'dg2_released'), 'rho_abc')
N['AbcFtCtrlTop'] = v(row('E3', 'abc', 'deepgate2', 'dg2_control', '5 ep, train_pi=shared'), 'top1_abc')
N['AbcFtEqTop'] = v(row('E3', 'abc', 'deepgate2', 'dg2_eqalign', 'lambda=0.2, 5 ep, train_pi=shared'), 'top1_abc')
N['AbcFtEqTopDc'] = fam('runs/E3/final/pi_shared/dg2_eqalign_l0.2_e5_s*', ['A2_dc2'])
N['AbcFtCtrlTopDc'] = fam('runs/E3/final/pi_shared/dg2_control_e5_s*', ['A2_dc2'])
# ISCAS
N['AbcIsBaseTop'], N['AbcIsOursTop'] = v(row('E1a', 'abc_iscas', D64, 'base'), 'top1_abc'), v(row('E1a', 'abc_iscas', D64, 'eqalign_ph'), 'top1_abc')
N['AbcIsFtCtrlTop'] = v(row('E3', 'abc_iscas', 'deepgate2', 'dg2_control', '5 ep, train_pi=shared'), 'top1_abc')
N['AbcIsFtEqTop'] = v(row('E3', 'abc_iscas', 'deepgate2', 'dg2_eqalign', 'lambda=0.2, 5 ep, train_pi=shared'), 'top1_abc')
# data
st = json.load(open(os.path.join(X, 'data/abc_regen.stats.json')))
N['AbcVariants'] = st['variants_compared']; N['AbcIdentical'] = st['identical']
json.dump(N, open(os.path.join(OUT_DIR, 'e17_numbers.json'), 'w'), indent=1)
for f in ('summary.csv', 'comparisons.csv', 'claims.md', 'report.md'):
    os.system(f'cp {X}/results/E17/{f} {OUT_DIR}/')


def fmt(k, x):
    if isinstance(x, int):
        return f'{x:,}'.replace(',', '{,}')
    if 'Rho' in k:
        return f'{x:.2f}'
    if 'DMAE' in k:
        return f'{x:.3f}'
    return f'{x:.1f}'


L = ['% generated by eqb_gpu/make_e17.py from the server results of E17 (certified ABC rewrites); do not edit']
L += [f'\\newcommand{{\\{k}}}{{{fmt(k, x)}}}' for k, x in N.items()]
open(OUT_TEX, 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))

# ---- appendix table: per family, restructured Top-1 (%) and rho, EPFL
FAMS = [('resyn2', ['A1_resyn2']), ('dc2', ['A2_dc2']), ('compress2rs', ['A3_compress2rs']), ('LUT round trip', ['A4_lutmap']),
        ('all four', ['A1_resyn2', 'A2_dc2', 'A3_compress2rs', 'A4_lutmap'])]
MODELS = [('Baseline', 'runs/E1a/gru_d64_r2/base_lr0.002_s*'), ('Augmentation', 'runs/E1a/gru_d64_r2/aug_lr0.002_s*'),
          ('\\ours', 'runs/E1a/gru_d64_r2/eqalign_ph_l0.2_lr0.002_s*'),
          ('DG2 FT, own loss', 'runs/E3/final/pi_shared/dg2_control_e5_s*'),
          ('DG2 FT, \\ours', 'runs/E3/final/pi_shared/dg2_eqalign_l0.2_e5_s*')]


def famrho(pattern, kinds):
    vals = []
    for f in sorted(glob.glob(os.path.join(X, pattern, 'raw_abc.pkl'))):
        g = group_metrics(pickle.load(open(f, 'rb')), kinds=kinds)
        vals.append(np.nanmean(g['incons_rs']) / np.nanmean(g['err_rs']))
    return float(np.mean(vals))


T = ['\\begin{tabular}{l' + 'cc' * len(FAMS) + '}', '\\toprule',
     ' & ' + ' & '.join(f'\\multicolumn{{2}}{{c}}{{{n}}}' for n, _ in FAMS) + ' \\\\',
     'Model & ' + ' & '.join(['Top-1 & $\\rho$'] * len(FAMS)) + ' \\\\', '\\midrule']
for name, pat in MODELS:
    if name.startswith('DG2 FT, own'):
        T.append('\\midrule')
    T.append(name + ' & ' + ' & '.join(f'{fam(pat, k):.1f} & {famrho(pat, k):.2f}' for _, k in FAMS) + ' \\\\')
T += ['\\bottomrule', '\\end{tabular}']
open('work/paper/tab_app_abc.tex', 'w').write('\n'.join(T) + '\n')
print('\n'.join(T))
